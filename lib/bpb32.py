#!/usr/bin/env python3
import struct, math
import data, bpb, timestamp


# =============================================================================
# Extended BPB structure for FAT32 volumes
# -----------------------------------------------------------------------------
# If the volume has been formatted FAT32, the remainder of the BPB
#
# =============================================================================
class BPB32(bpb.BPB):
    """
    If the volume has been formatted FAT32, the remainder of the BPB
    structure must be as described below:
    """

    # This field is only defined for FAT32 media and does not exist
    # on FAT12 and FAT16 media.

    # Bits 4-6 -- Reserved.

    # in bits 0-3.
    # Bits 8-15 -- Reserved.
    FLAGS = {
        # Bits 0-3 - Zero-based number of active FAT. Only valid if mirroring
        # is disabled.
        "ACTIVE": 0xE000,

        # Bit 7 -- 0 means the FAT is mirrored at runtime into all FATs.
        #       -- 1 means only one FAT is active; it is the one referenced
        "MIRRORED": 0x0100,
    }

    ALL_FLAGS = FLAGS["ACTIVE"] | FLAGS["MIRRORED"]

    def __init__(self, data_in: bytearray | memoryview, endianness_in: str,
                 sector_in: int = 0, size_in: int = int(0.5 * data.Data._KiB)):
        """
        """
        super().__init__(data_in, endianness_in, sector_in, size_in)

    def format(self, volume_label_in: str = bpb.BPB._NO_VOLLAB,
               bytes_per_sec_in: int = 512, media_in: int = 0xF8):
        self.BS_FilSysType = "FAT32"
        super().format(bytes_per_sec_in, media_in)

        # Number of reserved sectors in the reserved region of the volume
        # starting at the first sector of the volume. This field is used to
        # align the start of the data area to integral multiples of the cluster
        # size with respect to the start of the partition/media. This field
        # must not be 0 and can be any non-zero value. This field should
        # typically be used to align the start of the data area (cluster #2)
        # to the desired alignment unit, typically cluster size.
        self.BPB_RsvdSecCnt = 32

        # The below computes how many sectors the FAT takes up to enable
        # setting the BPB_FATSz16 or BPB_FATSz32 fields (see Section 4 for a
        # description of the FAT). At this point, it is assumed that
        # BPB_RootEntCnt, BPB_RsvdSecCnt, and BPB_NumFATs are appropriately
        # set. It is also assumed that DskSize is the size of the volume that
        # will be reflected in BPB_TotSec32 or BPB_TotSec16.
        # temp1 = self.disk_size - (self.BPB_RsvdSecCnt + self.RootDirSectors)
        # temp2 = (256 * self.BPB_SecPerClus) + self.BPB_NumFATs
        # self.BPB_FATSz32 = int((temp1 + (temp2 - 1)) / temp2)
        self.BPB_FATSz32 = self._compute_fat_size(4.0)

        # FATs are mirrored at runtime.
        self.BPB_ExtFlags = 0x0

        # Must be set to 0x0.
        self.BPB_FSVer = 0x00

        # This is set to the cluster number of the first cluster of the root
        # directory, This value should be 2 or the first usable (not bad)
        # cluster available thereafter.
        self.BPB_RootClus = 2

        # Sector number of FSINFO structure in the reserved area of the FAT32
        # volume. Usually 1. NOTE: There is a copy of the FSINFO structure in
        # the sequence of backup boot sectors, but only the copy pointed to by
        # this field is kept up to date (i.e., both the primary and backup boot
        # record point to the same FSINFO sector).
        self.BPB_FSInfo = 1

        # This can be 0 or 6. Set 6 if there is a backup in the 6th sector. For
        # now, we dont know if there is one. So, set 0.
        self.BPB_BkBootSec = 6

        # Set value to 0x80 or 0x00.
        if self.BPB_Media == 0xF8:
            self.BS_DrvNum = 0x80
        else:
            self.BS_DrvNum = 0x00

        # This ID should be generated by simply combining the current date and
        # time into a 32-bit value.
        self.BS_VolID = timestamp.Timestamp().id

        # Volume label. This field matches the 11-byte volume label recorded in
        # the root directory.
        self.BS_VolLab = volume_label_in

        # Format The Boot Sector
        try:
            with open("boot.bin", "rb") as file:
                try:
                    self.BS_BootCode = bytearray(file.read())
                finally:
                    file.close()
        except FileNotFoundError as _:
            pass

        # Set to 0x55 (at byte offset 510) and 0xAA (at byte offset 511) to
        # indicate that the boot sector is valid.
        self.Signature_word = self._SIGNATURE

    @property
    def BPB_FATSz32(self) -> int:
        """
        Name             | Offset (Byte)     | Size (Bytes)  |
        ------------------------------------------------------
        BPB_FATSz32      | 36                | 4             |
        ------------------------------------------------------
        This field is only defined for FAT32 media and does not exist
        on FAT12 and FAT16 media. This field is the FAT32 32-bit count
        of sectors occupied by ONE FAT. BPB_FATSz16 must be 0.

        :return: int: The FAT32 32-bit count of sectors occupied by
        ONE FAT.
        """
        return struct.unpack_from(
            f"{self.endianness}L",
            self.data, 36)[0]

    @BPB_FATSz32.setter
    def BPB_FATSz32(self, size_in: int):
        """
        Name             | Offset (Byte)     | Size (Bytes)  |
        ------------------------------------------------------
        BPB_FATSz32      | 36                | 4             |
        ------------------------------------------------------
        This field is only defined for FAT32 media and does not exist
        on FAT12 and FAT16 media. This field is the FAT32 32-bit count
        of sectors occupied by ONE FAT. BPB_FATSz16 must be 0.

        :param size_in: int: The FAT32 32-bit count of sectors occupied by ONE
        FAT.
        """

        # Note that BPB_FATSz16 must be 0 for media formatted FAT32.
        if size_in > 0:
            self.BPB_FATSz16 = 0

        struct.pack_into(
            f"{self.endianness}L", self.data,
            36, size_in)

    @property
    def BPB_ExtFlags(self) -> int:
        """
        Name             | Offset (Byte)     | Size (Bytes)  |
        ------------------------------------------------------
        BPB_ExtFlags     | 40                | 2             |
        ------------------------------------------------------
        This field is only defined for FAT32 media and does not exist
        on FAT12 and FAT16 media.
        Bits 0-3 - Zero-based number of active FAT. Only valid if mirroring
        is disabled.
        Bits 4-6 -- Reserved.
        Bit 7 -- 0 means the FAT is mirrored at runtime into all FATs.
        -- 1 means only one FAT is active; it is the one referenced
        in bits 0-3.
        Bits 8-15 -- Reserved.

        :return: BPB_ExtFlags: int
        """
        return struct.unpack_from(
            f"{self.endianness}H",
            self.data, 40)[0]

    @BPB_ExtFlags.setter
    def BPB_ExtFlags(self, flags_in: int):
        """
        Name             | Offset (Byte)     | Size (Bytes)  |
        ------------------------------------------------------
        BPB_ExtFlags     | 40                | 2             |
        ------------------------------------------------------
        This field is only defined for FAT32 media and does not exist
        on FAT12 and FAT16 media.
        Bits 0-3 - Zero-based number of active FAT. Only valid if mirroring
        is disabled.
        Bits 4-6 -- Reserved.
        Bit 7 -- 0 means the FAT is mirrored at runtime into all FATs.
        -- 1 means only one FAT is active; it is the one referenced
        in bits 0-3.
        Bits 8-15 -- Reserved.

        :param flags_in: BPB_ExtFlags: int
        """
        struct.pack_into(
            f"{self.endianness}H", self.data,
            40, (flags_in & self.ALL_FLAGS))

    @property
    def BPB_FSVer(self) -> tuple[int, int]:
        """
        Name             | Offset (Byte)     | Size (Bytes)  |
        ------------------------------------------------------
        BPB_FSVer        | 42                | 2             |
        ------------------------------------------------------
        This field is only defined for FAT32 media and does not exist
        on FAT12 and FAT16 media. High byte is major revision number.
        Low byte is minor revision number. This is the version number
        of the FAT32 volume. This supports the ability to extend the
        FAT32 media type in the future without worrying about old FAT32
        drivers mounting the volume. This document defines the version
        to 0:0. If this field is non-zero, back-level Windows versions
        will not mount the volume.
        NOTE: Data utilities should respect this field and not operate
        on volumes with a higher major or minor version number than
        that for which they were designed. FAT32 file system drivers
        must check this field and not mount the volume if it does not
        contain a version number that was defined at the time the
        driver was written.

        :return: tuple(int, int) -> major, minor. High byte
        is major revision number. Low byte is minor revision number.
        """
        return struct.unpack_from(
            f"{self.endianness}2B",
            self.data, 42)

    @BPB_FSVer.setter
    def BPB_FSVer(self, version_in: int):
        """
        Name             | Offset (Byte)     | Size (Bytes)  |
        ------------------------------------------------------
        BPB_FSVer        | 42                | 2             |
        ------------------------------------------------------
        This field is only defined for FAT32 media and does not exist
        on FAT12 and FAT16 media. High byte is major revision number.
        Low byte is minor revision number. This is the version number
        of the FAT32 volume. This supports the ability to extend the
        FAT32 media type in the future without worrying about old FAT32
        drivers mounting the volume. This document defines the version
        to 0:0. If this field is non-zero, back-level Windows versions
        will not mount the volume.
        NOTE: Data utilities should respect this field and not operate
        on volumes with a higher major or minor version number than
        that for which they were designed. FAT32 file system drivers
        must check this field and not mount the volume if it does not
        contain a version number that was defined at the time the
        driver was written.

        :param version_in: int -> major, minor. High byte
        is major revision number. Low byte is minor revision number.
        """
        struct.pack_into(
            f"{self.endianness}H", self.data,
            42, version_in)

    @property
    def BPB_FSVerMajor(self) -> int:
        return self.BPB_FSVer[0]

    @property
    def BPB_FSVerMinor(self) -> int:
        return self.BPB_FSVer[1]

    @property
    def BPB_RootClus(self) -> int:
        """
        Name             | Offset (Byte)     | Size (Bytes)  |
        ------------------------------------------------------
        BPB_RootClus     | 44                | 4             |
        ------------------------------------------------------
        This field is only defined for FAT32 media and does not exist
        on FAT12 and FAT16 media. This is set to the cluster number of
        the first cluster of the root directory, usually 2 but not
        required to be 2.
        NOTE: Data utilities that change the location of the root
        directory should make every effort to place the first cluster
        of the root directory in the first non-bad cluster on the drive
        (i.e., in cluster 2, unless it’s marked bad). This is specified
        so that disk repair utilities can easily find the root
        directory if this field accidentally gets zeroed.

        :return: int: The cluster number of the first cluster of the
        root directory,
        """
        return struct.unpack_from(
            f"{self.endianness}L",
            self.data, 44)[0]

    @BPB_RootClus.setter
    def BPB_RootClus(self, cluster_in: int):
        """
        Name             | Offset (Byte)     | Size (Bytes)  |
        ------------------------------------------------------
        BPB_RootClus     | 44                | 4             |
        ------------------------------------------------------
        This field is only defined for FAT32 media and does not exist
        on FAT12 and FAT16 media. This is set to the cluster number of
        the first cluster of the root directory, usually 2 but not
        required to be 2.
        NOTE: Data utilities that change the location of the root
        directory should make every effort to place the first cluster
        of the root directory in the first non-bad cluster on the drive
        (i.e., in cluster 2, unless it’s marked bad). This is specified
        so that disk repair utilities can easily find the root
        directory if this field accidentally gets zeroed.

        :param cluster_in: int: The cluster number of the first cluster of the
        root directory,
        """
        struct.pack_into(
            f"{self.endianness}L", self.data,
            44, cluster_in)

    @property
    def BPB_FSInfo(self) -> int:
        """
        Name             | Offset (Byte)     | Size (Bytes)  |
        ------------------------------------------------------
        BPB_FSInfo       | 48                | 2             |
        ------------------------------------------------------
        Sector number of FSINFO structure in the reserved area of the FAT32
        volume. Usually 1.
        NOTE: There is a copy of the FSINFO structure in the sequence of backup
        boot sectors, but only the copy pointed to by this field is kept up to
        date (i.e., both the primary and backup boot record point to the same
        FSINFO sector).

        :return: int: Sector number of FSINFO structure in the reserved area of
        the FAT32 volume. Usually 1.
        """
        return struct.unpack_from(
            f"{self.endianness}H",
            self.data, 48)[0]

    @BPB_FSInfo.setter
    def BPB_FSInfo(self, sector_in: int):
        """
        Name             | Offset (Byte)     | Size (Bytes)  |
        ------------------------------------------------------
        BPB_FSInfo       | 48                | 2             |
        ------------------------------------------------------
        Sector number of FSINFO structure in the reserved area of the FAT32
        volume. Usually 1.
        NOTE: There is a copy of the FSINFO structure in the sequence of backup
        boot sectors, but only the copy pointed to by this field is kept up to
        date (i.e., both the primary and backup boot record point to the same
        FSINFO sector).

        :param sector_in: int: Sector number of FSINFO structure in the
        reserved area of the FAT32 volume. Usually 1.
        """
        struct.pack_into(
            f"{self.endianness}H", self.data,
            48, sector_in)

    @property
    def BPB_BkBootSec(self) -> int:
        """
        Name             | Offset (Byte)     | Size (Bytes)  |
        ------------------------------------------------------
        BPB_BkBootSec    | 50                | 2             |
        ------------------------------------------------------
        Set to 0 or 6. If non-zero, indicates the sector number in the
        reserved area of the volume of a copy of the boot record.

        :return: int: The sector number of the volume of a copy of the
        boot sector.
        """
        return struct.unpack_from(
            f"{self.endianness}H",
            self.data, 50)[0]

    @BPB_BkBootSec.setter
    def BPB_BkBootSec(self, sector_in: int):
        """
        Name             | Offset (Byte)     | Size (Bytes)  |
        ------------------------------------------------------
        BPB_BkBootSec    | 50                | 2             |
        ------------------------------------------------------
        Set to 0 or 6. If non-zero, indicates the sector number in the reserved
        area of the volume of a copy of the boot record.

        :param sector_in: int: The sector number of the volume of a copy of the
        boot sector.
        """
        struct.pack_into(
            f"{self.endianness}H", self.data,
            50, sector_in)

    @property
    def BS_DrvNum(self) -> int:
        """
        Name             | Offset (Byte)     | Size (Bytes)  |
        ------------------------------------------------------
        BS_DrvNum        | 64                | 1             |
        ------------------------------------------------------
        Int 0x13 drive number (e.g. 0x80). This field supports MS-DOS
        bootstrap and is set to the INT 0x13 drive number of the media
        (0x00 for floppy disks, 0x80 for hard disks).
        NOTE: This field is actually operating system specific.

        This field has the same definition as it does for FAT12 and
        FAT16 media. The only difference for FAT32 media is that the
        field is at a different offset in the boot sector.

        :return: int: Int 0x13 drive number.
        """
        return struct.unpack_from(
            f"{self.endianness}B",
            self.data, 64)[0]

    @BS_DrvNum.setter
    def BS_DrvNum(self, number_in: int):
        """
        Name             | Offset (Byte)     | Size (Bytes)  |
        ------------------------------------------------------
        BS_DrvNum        | 64                | 1             |
        ------------------------------------------------------
        Int 0x13 drive number (e.g. 0x80). This field supports MS-DOS
        bootstrap and is set to the INT 0x13 drive number of the media
        (0x00 for floppy disks, 0x80 for hard disks).
        NOTE: This field is actually operating system specific.

        This field has the same definition as it does for FAT12 and
        FAT16 media. The only difference for FAT32 media is that the
        field is at a different offset in the boot sector.

        :param number_in: int: Int 0x13 drive number.
        """
        if number_in == 0x00 or number_in == 0x80:
            struct.pack_into(
                f"{self.endianness}B",  self.data,
                64, number_in)
        else:
            raise ValueError(
                f"Error: Invalid BS_DrvNum: {number_in}\n"
                f"Must Be: 0x00 or 0x80.")

    @property
    def BS_BootSig(self) -> int:
        """
        Name             | Offset (Byte)     | Size (Bytes)  |
        ------------------------------------------------------
        BS_BootSig       | 66                | 1             |
        ------------------------------------------------------
        Extended boot signature (0x29). This is a signature byte
        indicates that the following three fields are present.

        :return: BS_BootSig: byte
        """
        return struct.unpack_from(
            f"{self.endianness}B",
            self.data, 66)[0]

    @BS_BootSig.setter
    def BS_BootSig(self, signature_in: int):
        """
        Name             | Offset (Byte)     | Size (Bytes)  |
        ------------------------------------------------------
        BS_BootSig       | 66                | 1             |
        ------------------------------------------------------
        Extended boot signature (0x29). This is a signature byte
        indicates that the following three fields are present.

        :param signature_in: int: This is a signature byte. 0x29
        indicates that the following three fields are present.
        """
        if signature_in != 0x00 and signature_in != 0x29:
            raise ValueError(
                f"Error: Invalid BS_BootSig: {signature_in}\n"
                f"Must be 0x00 or 0x29")

        struct.pack_into(
            f"{self.endianness}B", self.data,
            66, signature_in)

    @property
    def BS_VolID(self) -> int:
        """
        Name             | Offset (Byte)     | Size (Bytes)  |
        ------------------------------------------------------
        BS_VolID         | 67                | 4             |
        ------------------------------------------------------
        Volume serial number. This field, together with BS_VolLab,
        supports volume tracking on removable media. These values
        allow FAT file system drivers to detect that the wrong disk is
        inserted in a removable drive. This ID is usually generated by
        simply combining the current date and time into a 32-bit value.

        :return: int: The volume id of this FAT.
        """
        return struct.unpack_from(
            f"{self.endianness}L",
            self.data, 67)[0]

    @BS_VolID.setter
    def BS_VolID(self, id_in: int):
        """
        Name             | Offset (Byte)     | Size (Bytes)  |
        ------------------------------------------------------
        BS_VolID         | 67                | 4             |
        ------------------------------------------------------
        Volume serial number. This field, together with BS_VolLab,
        supports volume tracking on removable media. These values
        allow FAT file system drivers to detect that the wrong disk is
        inserted in a removable drive. This ID is usually generated by
        simply combining the current date and time into a 32-bit value.

        :param id_in: int: The volume id of this FAT.
        """
        # Set value to 0x29 if either BS_VolID, BS_VolLab, or BS_FilSysType
        # fields are non-zero.
        self.BS_BootSig = 0x29

        struct.pack_into(
            f"{self.endianness}L", self.data,
            67, id_in)

    @property
    def BS_VolLab(self) -> str:
        """
        Name             | Offset (Byte)     | Size (Bytes)  |
        ------------------------------------------------------
        BS_VolLab        | 71                | 11            |
        ------------------------------------------------------
        Volume label. This field matches the 11-byte volume label
        recorded in the root directory.
        NOTE: FAT file system drivers should make sure that they update
        this field when the volume label file in the root directory has
        its name changed or created. The setting for this field when
        there is no volume label is the string “NO NAME ”.

        :return: str: The 11 Character volume label recorded in the
        root directory.
        """
        return struct.unpack_from(
            f"{self.endianness}11s",
            self.data, 71)[0].rstrip(b"\x00").decode('ascii')

    @BS_VolLab.setter
    def BS_VolLab(self, volume_label_in: str):
        """
        Name             | Offset (Byte)     | Size (Bytes)  |
        ------------------------------------------------------
        BS_VolLab        | 71                | 11            |
        ------------------------------------------------------
        Volume label. This field matches the 11-byte volume label
        recorded in the root directory.
        NOTE: FAT file system drivers should make sure that they update
        this field when the volume label file in the root directory has
        its name changed or created. The setting for this field when
        there is no volume label is the string “NO NAME ”.

        :param volume_label_in: The 11 Character volume label recorded in the
        root directory.
        """
        # Set value to 0x29 if either BS_VolID, BS_VolLab, or BS_FilSysType
        # fields are non-zero.
        self.BS_BootSig = 0x29

        struct.pack_into(
            f"{self.endianness}11s", self.data,
            71, f"{volume_label_in: <11}".encode("ascii"))

    @property
    def BS_FilSysType(self) -> str:
        """
        Name             | Offset (Byte)     | Size (Bytes)  |
        ------------------------------------------------------
        BS_FilSysType    | 82                | 8             |
        ------------------------------------------------------
        One of the strings “FAT12 ”, “FAT16 ”, or “FAT ”.

        NOTE: Many people think that the string in this field has
        something to do with the determination of what type of FAT—
        FAT12, FAT16, or FAT32 — that the volume has. This is not true.
        You will note from its name that this field is not actually
        part of the BPB. This string is informational only and is not
        used by Microsoft file system drivers to determine FAT type
        because it is frequently not set correctly or is not present.
        See the FAT Type Determination section of this document. This
        string should be set based on the FAT type though, because some
        non-Microsoft FAT file system drivers do look at it.

        :return: str (Should be "FAT32   ")
        """
        return struct.unpack_from(
            f"{self.endianness}8c",
            self.data, 82)[0].rstrip(b"\x00").decode('ascii')

    @BS_FilSysType.setter
    def BS_FilSysType(self, type_in: str):
        """
        Name             | Offset (Byte)     | Size (Bytes)  |
        ------------------------------------------------------
        BS_FilSysType    | 82                | 8             |
        ------------------------------------------------------
        One of the strings “FAT12 ”, “FAT16 ”, or “FAT ”.

        NOTE: Many people think that the string in this field has
        something to do with the determination of what type of FAT—
        FAT12, FAT16, or FAT32 — that the volume has. This is not true.
        You will note from its name that this field is not actually
        part of the BPB. This string is informational only and is not
        used by Microsoft file system drivers to determine FAT type
        because it is frequently not set correctly or is not present.
        See the FAT Type Determination section of this document. This
        string should be set based on the FAT type though, because some
        non-Microsoft FAT file system drivers do look at it.

        :param type_in: str (Should be "FAT32   ")
        """
        # Set value to 0x29 if either BS_VolID, BS_VolLab, or BS_FilSysType
        # fields are non-zero.
        self.BS_BootSig = 0x29

        struct.pack_into(
            f"{self.endianness}8s",
            self.data,
            82,
            f"{type_in.upper(): <8}".encode("ascii"))

    @property
    def BS_BootCode(self) -> memoryview:
        """
        Name             | Offset (Byte)     | Size (Bytes)  |
        ------------------------------------------------------
        BS_BootCode      | 90                | 420           |
        ------------------------------------------------------
        Bootstrap program. It is platform dependent and filled with zero
        when not used.

        :return: memoryview: The boot code.
        """
        if self.BS_BootSig == 0x29:
            offset = 90
        else:
            offset = 67
        return self.data[offset:510]

    @BS_BootCode.setter
    def BS_BootCode(self, code_in: bytearray | memoryview):
        """
        Name             | Offset (Byte)     | Size (Bytes)  |
        ------------------------------------------------------
        BS_BootCode      | 90                | 420           |
        ------------------------------------------------------
        Bootstrap program. It is platform dependent and filled with zero
        when not used.

        :param code_in:
        """
        if self.BS_BootSig == 0x29:
            offset = 90
        else:
            offset = 67
        length = 510 - offset

        if len(code_in) <= length:
            self.data[offset:510] = code_in[:length]
        else:
            raise ValueError(
                f"Error: Boot Code Is Too Long: {len(code_in)} Byte(s)\n"
                f"Boot Code Must Be {510 - offset} Bytes or Less.")

    @property
    def data_sector(self) -> int:
        return (self.BPB_RsvdSecCnt + self.root_sectors +
                self.BPB_FATSz32 * self.BPB_NumFATs)

